export type DripCampaignStatus = 'Draft' | 'Active' | 'Paused' | 'Completed';

export type DripTriggerType = 'Time-Based' | 'Event-Based' | 'Behavior-Based';

export type DripStepAction = 'Send Email' | 'Send SMS' | 'Add Tag' | 'Wait' | 'Notify Owner' | 'Update Score';

export type DripEnrollmentOperator =
  | 'equals'
  | 'contains'
  | 'greater_than'
  | 'less_than'
  | 'is_true'
  | 'is_false';

export interface DripEnrollmentRule {
  id: string;
  field: string;
  operator: DripEnrollmentOperator;
  value: string;
}

/**
 * Editable setup fields only. Opened / clicked / converted / active / completed
 * are never collected from operators — they are system telemetry.
 */
export interface DripCampaignEditablePayload {
  title: string;
  description: string;
  triggerType: DripTriggerType;
  triggerDetail: string;
  targetPersona: string;
  enrollmentRules: DripEnrollmentRule[];
  goal: string;
  notes?: string;
}

export interface DripStepTelemetry {
  delivered: number;
  opened: number;
  clicked: number;
  converted: number;
  skipped: number;
  failed: number;
}

export interface DripSequenceStep {
  id: string;
  order: number;
  delayLabel: string;
  delayHours: number;
  actionType: DripStepAction;
  title: string;
  description: string;
  subject?: string;
  tagName?: string;
  telemetry: DripStepTelemetry;
}

/**
 * Live funnel counts generated by webhooks / send pipeline. Never form inputs.
 */
export interface DripCampaignTelemetry {
  enrolledLeads: number;
  activeLeads: number;
  completedLeads: number;
  unsubscribedLeads: number;
  opened: number;
  clicked: number;
  converted: number;
  bounced: number;
  openRate: number;
  clickRate: number;
  conversionRate: number;
  completionRate: number;
}

export interface DripCampaign extends DripCampaignEditablePayload {
  _id: string;
  status: DripCampaignStatus;
  steps: DripSequenceStep[];
  telemetry: DripCampaignTelemetry;
  owner: string;
  createdAt: string;
  updatedAt: string;
  lastRunAt?: string;
}

export interface DripHubSummary {
  totalSequences: number;
  activeSequences: number;
  totalActiveLeads: number;
  averageOpenRate: number;
  averageClickRate: number;
  averageConversionRate: number;
}

