export function deriveStepRates(step: DripSequenceStep) {
  const delivered = Math.max(step.telemetry.delivered, 0);
  const openRate = delivered === 0 ? 0 : (step.telemetry.opened / delivered) * 100;
  const clickRate = delivered === 0 ? 0 : (step.telemetry.clicked / delivered) * 100;
  const conversionRate = delivered === 0 ? 0 : (step.telemetry.converted / delivered) * 100;
  return {
    openRate: Number(openRate.toFixed(1)),
    clickRate: Number(clickRate.toFixed(1)),
    conversionRate: Number(conversionRate.toFixed(1)),
  };
}

export function summarizeDripCampaigns(campaigns: DripCampaign[]): DripHubSummary {
  const active = campaigns.filter((c) => c.status === 'Active');
  const withSends = campaigns.filter((c) => (c.telemetry?.enrolledLeads || 0) > 0);
  const avg = (picker: (c: DripCampaign) => number) =>
    withSends.length === 0
      ? 0
      : Number((withSends.reduce((sum, c) => sum + picker(c), 0) / withSends.length).toFixed(1));

  return {
    totalSequences: campaigns.length,
    activeSequences: active.length,
    totalActiveLeads: campaigns.reduce((sum, c) => sum + (c.telemetry?.activeLeads || 0), 0),
    averageOpenRate: avg((c) => c.telemetry?.openRate || 0),
    averageClickRate: avg((c) => c.telemetry?.clickRate || 0),
    averageConversionRate: avg((c) => c.telemetry?.conversionRate || 0),
  };
}

export function emptyStepTelemetry(): DripStepTelemetry {
  return { delivered: 0, opened: 0, clicked: 0, converted: 0, skipped: 0, failed: 0 };
}

